function isNodeSkippable(node) {
  if (!node || !node.parentElement) return true;
  const parent = node.parentElement;

  const tag = parent.tagName.toLowerCase();
  if (tag === 'script' || tag === 'style' || tag === 'code' || tag === 'pre') return true;

  if (parent.closest('.notranslate, [translate="no"], .goog-te-combo')) return true;

  if (tag === 'input' || tag === 'textarea') return true;

  return false;
}

function walkAndTranslate(rootNode, lang) {
  if (!rootNode) return;

  const walker = document.createTreeWalker(
    rootNode,
    NodeFilter.SHOW_TEXT,
    {
      acceptNode(node) {
        if (isNodeSkippable(node)) return NodeFilter.FILTER_REJECT;
        if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_SKIP;
        return NodeFilter.FILTER_ACCEPT;
      }
    }
  );

  const textNodes = [];
  let current;
  while ((current = walker.nextNode())) {
    textNodes.push(current);
  }

  for (const node of textNodes) {
    if (node.__mc_orig === undefined) {
      node.__mc_orig = node.nodeValue;
    }

    if (lang === 'en') {
      if (node.nodeValue !== node.__mc_orig) {
        node.nodeValue = node.__mc_orig;
      }
    } else {
      const translated = translateText(node.__mc_orig, lang);
      if (node.nodeValue !== translated) {
        node.nodeValue = translated;
      }
    }
  }

  // Also translate placeholders and titles on inputs/buttons
  const attrElements = rootNode.querySelectorAll?.('input[placeholder], textarea[placeholder], [title]');
  if (attrElements) {
    attrElements.forEach(el => {
      if (el.closest('.notranslate, [translate="no"]')) return;

      if (el.placeholder) {
        if (el.__mc_orig_placeholder === undefined) {
          el.__mc_orig_placeholder = el.placeholder;
        }
        el.placeholder = (lang === 'en') 
          ? el.__mc_orig_placeholder 
          : translateText(el.__mc_orig_placeholder, lang);
      }

      if (el.title) {
        if (el.__mc_orig_title === undefined) {
          el.__mc_orig_title = el.title;
        }
        el.title = (lang === 'en')
          ? el.__mc_orig_title
          : translateText(el.__mc_orig_title, lang);
      }
    });
  }
}

function scheduleDomPass(targetContainer) {
  if (rafId) cancelAnimationFrame(rafId);
  rafId = requestAnimationFrame(() => {
    if (isSyncing) return;
    isSyncing = true;
    try {
      walkAndTranslate(targetContainer || document.getElementById('root') || document.body, currentLanguage);
    } catch (err) {
      console.warn('NLP DOM Translation pass notice:', err);
    } finally {
      isSyncing = false;
    }
  });
}

export function syncDomLanguage(langCode) {
  currentLanguage = langCode || 'en';

  const root = document.getElementById('root') || document.body;
  if (!root) return;

  walkAndTranslate(root, currentLanguage);

  if (!activeObserver && typeof MutationObserver !== 'undefined') {
    activeObserver = new MutationObserver((mutations) => {
      if (isSyncing || currentLanguage === 'en') return;

      let shouldUpdate = false;
      for (const m of mutations) {
        if (m.type === 'childList' && (m.addedNodes.length > 0)) {
          shouldUpdate = true;
          break;
        }
        if (m.type === 'characterData') {
          if (m.target && m.target.__mc_orig !== m.target.nodeValue) {
            m.target.__mc_orig = m.target.nodeValue;
            shouldUpdate = true;
            break;
          }
        }
      }

      if (shouldUpdate) {
        scheduleDomPass(root);
      }
    });

    activeObserver.observe(root, {
      childList: true,
      subtree: true,
      characterData: true
    });
  }

  setTimeout(() => {
    scheduleDomPass(root);
  }, 150);
}
