// Pre-compiled sorted keys for fast multi-word matching
const SORTED_PHRASE_KEYS = Object.keys(NLP_DICTIONARY).sort((a, b) => b.length - a.length);
const SORTED_KEYWORD_KEYS = Object.keys(KEYWORD_MAP).sort((a, b) => b.length - a.length);

/**
 * Translates a single text string into the target language.
 */
export function translateText(rawText, targetLang) {
  if (!rawText || targetLang === 'en') return rawText;

  const trimmed = rawText.trim();
  if (!trimmed) return rawText;

  // 1. Direct exact dictionary match
  if (NLP_DICTIONARY[trimmed] && NLP_DICTIONARY[trimmed][targetLang]) {
    const translated = NLP_DICTIONARY[trimmed][targetLang];
    return rawText.replace(trimmed, translated);
  }

  // 2. Keyword exact match
  if (KEYWORD_MAP[trimmed] && KEYWORD_MAP[trimmed][targetLang]) {
    const translated = KEYWORD_MAP[trimmed][targetLang];
    return rawText.replace(trimmed, translated);
  }

  // 3. Dynamic Regex Patterns
  // Pattern: "Level X (Y Pairs)"
  const levelPairsMatch = trimmed.match(/^Level\s+(\d+)\s*\((.*?)\s*Pairs\)$/i);
  if (levelPairsMatch) {
    const lvlNum = levelPairsMatch[1];
    const pairCount = levelPairsMatch[2];
    const lvlWord = KEYWORD_MAP['Level'][targetLang] || 'Level';
    const pairWord = KEYWORD_MAP['Pairs'][targetLang] || 'Pairs';
    return rawText.replace(trimmed, `${lvlWord} ${lvlNum} (${pairCount} ${pairWord})`);
  }

  // Pattern: "Level X"
  const levelMatch = trimmed.match(/^Level\s+(\d+)$/i);
  if (levelMatch) {
    const lvlNum = levelMatch[1];
    const lvlWord = KEYWORD_MAP['Level'][targetLang] || 'Level';
    return rawText.replace(trimmed, `${lvlWord} ${lvlNum}`);
  }

  // Pattern: "X New Connection Request(s)!"
  const connReqMatch = trimmed.match(/^(\d+)\s+New\s+Connection\s+Request(?:s)?!$/i);
  if (connReqMatch) {
    const count = connReqMatch[1];
    const labels = {
      "hi": `${count} नया कनेक्शन अनुरोध!`,
      "kn": `${count} ಹೊಸ ಸಂಪರ್ಕ ವಿನಂತಿ!`,
      "ta": `${count} புதிய இணைப்பு கோரிக்கை!`,
      "te": `${count} కొత్త కనెక్షన్ అభ్యర్థన!`,
      "bn": `${count} নতুন সংযোগের অনুরোধ!`,
      "mr": `${count} नवीन कनेक्शन विनंती!`,
      "gu": `${count} નવી કનેક્શન વિનંતી!`,
      "ml": `${count} പുതിയ കണക്ഷൻ അഭ്യർത്ഥന!`
    };
    return rawText.replace(trimmed, labels[targetLang] || trimmed);
  }

  // 4. Sub-phrase & Multi-token replacement
  let result = rawText;
  let modified = false;

  for (const phrase of SORTED_PHRASE_KEYS) {
    if (result.includes(phrase) && NLP_DICTIONARY[phrase][targetLang]) {
      result = result.replaceAll(phrase, NLP_DICTIONARY[phrase][targetLang]);
      modified = true;
    }
  }

  for (const kw of SORTED_KEYWORD_KEYS) {
    const regex = new RegExp(`\\b${kw}\\b`, 'g');
    if (regex.test(result) && KEYWORD_MAP[kw][targetLang]) {
      result = result.replace(regex, KEYWORD_MAP[kw][targetLang]);
      modified = true;
    }
  }

  return modified ? result : rawText;
}

